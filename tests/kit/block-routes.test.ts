import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { describe, expect, it } from 'vite-plus/test';

import { nextRouteFiles, planBlockRoutes, writeBlockRoutes } from '../../scripts/kit/block-routes';
import type { BlockMeta } from '../../scripts/kit/blocks';
import { hashFile, readLock, writeLock } from '../../scripts/kit/core';

const FRAMEWORK_FILES = ['app/[lang]/error.tsx', 'app/[lang]/not-found.tsx', 'app/global-not-found.tsx'];

const meta = (id: string, extra: Partial<BlockMeta> = {}): BlockMeta => ({
  id,
  title: id,
  level: 'template',
  family: 'test',
  description: id,
  tags: [],
  dependsOn: [],
  packages: {},
  routes: [],
  nav: [],
  ...extra,
});

const SYSTEM_PAGES = meta('system-pages', {
  routes: [
    { path: '*', component: 'NotFoundPage', layout: 'bare', titleKey: 'notFound.title' },
    { path: '/maintenance', component: 'MaintenancePage', layout: 'bare', titleKey: 'maintenance.title' },
    { path: '/no-access', component: 'NoAccessPage', layout: 'app', titleKey: 'noAccess.title' },
  ],
  errorElement: 'ServerErrorPage',
});

/** A Next app with a lock: no generated files yet unless `files` says so. */
const app = (files: Record<string, string> = {}, generated?: Record<string, string>) => {
  const root = mkdtempSync(path.join(tmpdir(), 'block-routes-'));
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), text);
  }
  writeLock(root, 'aaaaaaa', new Map(), [], { starter: 'mohammadsafia/rsk-next-starter', target: 'next', generated });
  return root;
};
const read = (root: string, file: string) => readFileSync(path.join(root, file), 'utf8');

describe('nextRouteFiles', () => {
  it('with no blocks, writes the starter defaults and nothing else', () => {
    const files = nextRouteFiles([]);
    expect([...files.keys()].sort()).toEqual(FRAMEWORK_FILES);
    for (const source of files.values()) expect(source.split('\n')[0]).toMatch(/^\/\/ Generated by kit:add: the starter's default/);
  });

  it('maps app, bare, param and catch-all routes to App Router files', () => {
    const files = nextRouteFiles([
      SYSTEM_PAGES,
      meta('patients', { routes: [{ path: '/patients/:id', component: 'PatientPage', layout: 'app' }] }),
    ]);
    expect([...files.keys()].sort()).toEqual(
      [
        ...FRAMEWORK_FILES,
        'app/[lang]/(app)/no-access/page.tsx',
        'app/[lang]/(app)/patients/[id]/page.tsx',
        'app/[lang]/maintenance/page.tsx',
      ].sort(),
    );
    expect(files.get('app/global-not-found.tsx')?.split('\n')[0]).toBe(
      '// Generated by kit:add from the "system-pages" block. Edit it and kit:add/kit:remove leave it to you.',
    );
  });

  it('an app page checks the session, titles itself from the block copy and renders the block component', () => {
    const page = nextRouteFiles([SYSTEM_PAGES]).get('app/[lang]/(app)/no-access/page.tsx') ?? '';
    expect(page).toContain("import { NoAccessPage } from '@blocks/system-pages';");
    expect(page).toContain("import ar from '@locales/ar/block-system-pages.json';");
    expect(page).toContain('await requireSession(lang)');
    expect(page).toContain("(lang === 'ar' ? ar : en).noAccess.title");
    expect(page).toContain('return <NoAccessPage />;');
    expect(page).not.toContain('../');
    // A page outside the shell is public.
    expect(nextRouteFiles([SYSTEM_PAGES]).get('app/[lang]/maintenance/page.tsx')).not.toContain('requireSession');
  });

  it('a route without a title key renders without metadata', () => {
    const page = nextRouteFiles([meta('x', { routes: [{ path: '/x', component: 'XPage', layout: 'bare' }] })]).get('app/[lang]/x/page.tsx');
    expect(page).not.toContain('generateMetadata');
    expect(page).toContain('return <XPage />;');
  });

  it('the 404 renders the block page in the providers on the server, and notFound() lands on it in the browser', () => {
    const files = nextRouteFiles([SYSTEM_PAGES]);
    const global = files.get('app/global-not-found.tsx') ?? '';
    expect(global).toContain("import { Providers } from './[lang]/providers';");
    expect(global).toContain('<NotFoundPage />');
    expect(global).toContain("(lang === 'ar' ? ar : en).notFound.title");
    expect(files.get('app/[lang]/not-found.tsx')).toMatch(/'use client';[\s\S]*<NotFoundPage \/>/);
  });

  it("the error block feeds error.tsx with Next's reset", () => {
    const error = nextRouteFiles([SYSTEM_PAGES]).get('app/[lang]/error.tsx') ?? '';
    expect(error).toContain("'use client';");
    expect(error).toContain('<ServerErrorPage error={error} retry={reset} />');
  });
});

describe('planBlockRoutes', () => {
  it('writes what is missing or still generated, and leaves unchanged files alone', () => {
    const fresh = app();
    expect([...planBlockRoutes(fresh, []).write.keys()].sort()).toEqual(FRAMEWORK_FILES);
    const { generated } = writeBlockRoutes(fresh, []);
    writeLock(fresh, 'aaaaaaa', new Map(), [], { generated });
    expect(planBlockRoutes(fresh, [])).toEqual({ write: new Map(), remove: [], refused: [] });
    // Adding the block replaces the defaults it claims, since they are still as generated.
    expect([...planBlockRoutes(fresh, [SYSTEM_PAGES]).write.keys()]).toEqual(expect.arrayContaining(FRAMEWORK_FILES));
  });

  it('refuses a file the app changed, and one kit:add never wrote', () => {
    const fresh = app();
    const { generated } = writeBlockRoutes(fresh, []);
    writeLock(fresh, 'aaaaaaa', new Map(), [], { generated });
    writeFileSync(path.join(fresh, 'app/[lang]/not-found.tsx'), 'export default function Mine() { return null; }\n');
    mkdirSync(path.join(fresh, 'app/[lang]/maintenance'), { recursive: true });
    writeFileSync(path.join(fresh, 'app/[lang]/maintenance/page.tsx'), 'export default function Mine() { return null; }\n');
    expect(planBlockRoutes(fresh, [SYSTEM_PAGES]).refused.sort()).toEqual(['app/[lang]/maintenance/page.tsx', 'app/[lang]/not-found.tsx']);
  });

  it('removes a generated page no block wants any more, unless the app changed it', () => {
    const withBlock = app();
    const { generated } = writeBlockRoutes(withBlock, [SYSTEM_PAGES]);
    writeLock(withBlock, 'aaaaaaa', new Map(), [], { generated });
    expect(planBlockRoutes(withBlock, []).remove.sort()).toEqual([
      'app/[lang]/(app)/no-access/page.tsx',
      'app/[lang]/maintenance/page.tsx',
    ]);
    writeFileSync(path.join(withBlock, 'app/[lang]/maintenance/page.tsx'), '// mine\n');
    const plan = planBlockRoutes(withBlock, []);
    expect(plan.remove).toEqual(['app/[lang]/(app)/no-access/page.tsx']);
    expect(plan.refused).toEqual(['app/[lang]/maintenance/page.tsx']);
  });
});

describe('writeBlockRoutes', () => {
  it('records the hash of each file it wrote, keeps the ones it refused, and tidies emptied folders', () => {
    const root = app();
    const first = writeBlockRoutes(root, [SYSTEM_PAGES]);
    expect(first.kept).toEqual([]);
    expect(first.generated['app/[lang]/(app)/no-access/page.tsx']).toBe(hashFile(path.join(root, 'app/[lang]/(app)/no-access/page.tsx')));
    writeLock(root, 'aaaaaaa', new Map(), [], { generated: first.generated });
    const second = writeBlockRoutes(root, []);
    expect(existsSync(path.join(root, 'app/[lang]/(app)/no-access'))).toBe(false);
    expect(Object.keys(second.generated).sort()).toEqual(FRAMEWORK_FILES);
    expect(read(root, 'app/[lang]/error.tsx').split('\n')[0]).toMatch(/the starter's default/);
  });
});

describe('the lock', () => {
  it('keeps starter, target and generated when a write leaves them out, and an older lock byte for byte', () => {
    const root = app({}, { 'app/x.tsx': 'abc' });
    writeLock(root, 'bbbbbbb', new Map(), ['a']);
    expect(readLock(root)).toMatchObject({ target: 'next', generated: { 'app/x.tsx': 'abc' } });
    const old = mkdtempSync(path.join(tmpdir(), 'old-lock-'));
    writeLock(old, 'ccccccc', new Map([['src/a.ts', 'h']]), []);
    const before = read(old, 'kit.lock.json');
    writeLock(old, 'ccccccc', new Map([['src/a.ts', 'h']]), []);
    expect(read(old, 'kit.lock.json')).toBe(before);
    expect(before).not.toContain('generated');
  });
});
