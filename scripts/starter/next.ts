/**
 * Turns a built Vite starter tree into the Next.js starter: drops the Vite entry files (NEXT_DROP), rewrites the
 * app-owned config for Next (package.json, vite.config.ts for lint and tests only, tsconfig in the form next build
 * writes, CSS without the remote font import) and writes a static locale map. The kit's own files are untouched, so
 * both starters ship the same kit.
 */
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { NEXT_DROP, NEXT_DROP_SCRIPTS, NEXT_RUNTIME_DEPENDENCIES } from './manifest';

type Pkg = {
  description?: string;
  scripts: Record<string, string>;
  dependencies: Record<string, string>;
  devDependencies: Record<string, string>;
  sideEffects?: string[];
};

const SCRIPTS = {
  dev: 'next dev',
  build: 'next typegen && tsc -b && next build',
  start: 'next start',
  'a11y:audit': 'node scripts/a11y/audit.mjs --base http://localhost:3000 --seed api --lang-in path --signed-out /login,/forgot-password',
};

type Replacement = string | ((match: string, ...groups: string[]) => string);

const replaceIn = (out: string, file: string, find: string | RegExp, replace: Replacement) => {
  const full = path.join(out, file);
  const source = readFileSync(full, 'utf8');
  const next = typeof replace === 'string' ? source.replace(find, replace) : source.replace(find, replace);
  if (next === source)
    throw new Error(`next starter: "${String(find).slice(0, 60)}" not found in ${file} — update scripts/starter/next.ts`);
  writeFileSync(full, next);
};

const identifier = (lang: string, namespace: string) =>
  `${lang}${namespace.replace(/(^|[-_])(\w)/g, (_, _sep: string, letter: string) => letter.toUpperCase())}`;

/** src/locales/index.ts for a Next app: every namespace imported statically (a block's copy loads with the block). */
export function writeStaticLocales(out: string): void {
  const namespaces = (lang: string) =>
    readdirSync(path.join(out, 'src/locales', lang))
      .filter((file) => file.endsWith('.json') && !file.startsWith('block-'))
      .map((file) => file.replace(/\.json$/, ''))
      .sort((a, b) => a.localeCompare(b));
  const langs = ['en', 'ar'];
  const imports = langs.flatMap((lang) => namespaces(lang).map((ns) => `import ${identifier(lang, ns)} from './${lang}/${ns}.json';`));
  const map = (lang: string) =>
    [
      `const ${lang.toUpperCase()}: ResourceLanguage = {`,
      ...namespaces(lang).map((ns) => `  '${ns}': ${identifier(lang, ns)},`),
      '};',
    ].join('\n');
  const source = [
    '// Generated by starter:build: each namespace in src/locales/{en,ar} (a block brings its own block-*.json). When you',
    '// add a namespace, import it here too.',
    "import type { ResourceLanguage } from 'i18next';",
    '',
    ...imports,
    '',
    map('en'),
    '',
    map('ar'),
    '',
    'export const LOCALES = { EN, AR } as const;',
    '',
  ].join('\n');
  writeFileSync(path.join(out, 'src/locales/index.ts'), source);
}

export function nextTransform(out: string): void {
  for (const file of NEXT_DROP) rmSync(path.join(out, file), { recursive: true, force: true });

  // package.json: Next runs the app; Vite+ stays for lint, format and tests.
  const pkgFile = path.join(out, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgFile, 'utf8')) as Pkg;
  pkg.description = 'A Next.js app started from the RSK UI kit.';
  for (const name of NEXT_RUNTIME_DEPENDENCIES) {
    pkg.dependencies[name] = pkg.devDependencies[name];
    delete pkg.devDependencies[name];
  }
  delete pkg.dependencies['react-router'];
  delete pkg.devDependencies['@tailwindcss/vite'];
  for (const script of NEXT_DROP_SCRIPTS) delete pkg.scripts[script];
  Object.assign(pkg.scripts, SCRIPTS);
  pkg.sideEffects = ['*.css', './src/i18n.ts'];
  writeFileSync(pkgFile, `${JSON.stringify(pkg, null, 2)}\n`);

  // vite.config.ts: lint, format and tests only (Next builds with PostCSS for Tailwind).
  replaceIn(out, 'vite.config.ts', "import tailwindcss from '@tailwindcss/vite';\n", '');
  replaceIn(out, 'vite.config.ts', ', tailwindcss()])', '])');
  replaceIn(
    out,
    'vite.config.ts',
    "ignorePatterns: ['dist', 'registry', ",
    "ignorePatterns: ['dist', 'registry', '.next', 'next-env.d.ts', ",
  );
  replaceIn(out, 'vite.config.ts', "ignorePatterns: ['**/*.hbs', ", "ignorePatterns: ['.next/**', 'next-env.d.ts', '**/*.hbs', ");
  replaceIn(
    out,
    'vite.config.ts',
    "exclude: [...configDefaults.exclude, 'registry/**'],",
    "exclude: [...configDefaults.exclude, 'registry/**', '.next/**'],\n    // 'server-only' throws outside a server build; the tests import server modules directly.\n    alias: { 'server-only': path.resolve(__dirname, 'src/test/empty.ts') },",
  );

  // Aliases for the Next app's own modules: public settings and the server-only folder.
  replaceIn(
    out,
    'vite.config.ts',
    "      { find: '@api', replacement: path.resolve(__dirname, 'src/api') },",
    "      { find: '@api', replacement: path.resolve(__dirname, 'src/api') },\n      { find: '@env', replacement: path.resolve(__dirname, 'src/env') },\n      { find: '@server', replacement: path.resolve(__dirname, 'src/server') },",
  );
  replaceIn(
    out,
    'tsconfig.app.json',
    '"@api/*": ["./src/api/*"],',
    '"@api/*": ["./src/api/*"],\n      "@env": ["./src/env"],\n      "@server/*": ["./src/server/*"],',
  );

  // tsconfig in the form next build writes, so it never rewrites it.
  replaceIn(
    out,
    'tsconfig.app.json',
    '"types": ["vite/client", "node"],',
    '"types": ["vite/client", "node"],\n    "plugins": [{ "name": "next" }],',
  );
  replaceIn(
    out,
    'tsconfig.app.json',
    '"include": ["src"]',
    '"include": ["src", "app", "proxy.ts", "next-env.d.ts", ".next/types/**/*.ts", ".next/dev/types/**/*.ts"],\n  "exclude": ["node_modules"]',
  );
  replaceIn(out, 'tsconfig.node.json', /"include": \[([^\]]*)\]/, (_: string, list: string) => `"include": [${list}, "next.config.ts"]`);

  // next/font loads the families (app/[lang]/layout.tsx): no remote @import.
  const css = path.join(out, 'src/index.css');
  const lines = readFileSync(css, 'utf8').split('\n');
  if (!lines[0].includes('fonts.googleapis')) throw new Error('next starter: src/index.css no longer starts with the font @import');
  writeFileSync(css, lines.slice(1).join('\n').replace(/^\n+/, ''));

  writeStaticLocales(out);

  const gitignore = path.join(out, '.gitignore');
  writeFileSync(gitignore, `${readFileSync(gitignore, 'utf8').trimEnd()}\n\n# Next.js\n.next/\nnext-env.d.ts\n`);
  if (existsSync(path.join(out, 'vercel.json'))) throw new Error('next starter: vercel.json would deploy the docs site');
}
