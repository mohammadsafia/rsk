// @vitest-environment node
// The Next rules of docs/CODE_STANDARDS.md (§13) that a test can check, over this app's own files.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vite-plus/test';

const APP = path.join(process.cwd(), 'app');

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

const EXPORTS_METADATA = /export (async )?function generateMetadata\b|export const metadata\b/;

describe('Next standards', () => {
  it('13.4: every page under app/[lang] has metadata (generated block pages take the layout’s)', () => {
    const missing = walk(path.join(APP, '[lang]'))
      .filter((file) => path.basename(file) === 'page.tsx')
      .filter((file) => {
        const source = readFileSync(file, 'utf8');
        return !source.startsWith('// Generated by kit:add') && !EXPORTS_METADATA.test(source);
      })
      .map((file) => path.relative(process.cwd(), file));
    expect(missing).toEqual([]);
  });
});
