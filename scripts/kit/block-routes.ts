// A Next app's block routes: the App Router files its blocks need, generated like the block index. One server page per
// block route, and the 404 and error files (the starter's defaults until a block claims them). kit.lock.json's
// `generated` records each file's hash, so kit:add and kit:remove replace or delete one only while the app hasn't
// changed it; a file the app wrote itself, or edited, is never touched.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import type { BlockMeta, BlockRoute } from './blocks';
import { hashFile, readLock } from './core';

const TEMPLATES = path.join(import.meta.dirname, 'next');

const blockHeader = (id: string) => `// Generated by kit:add from the "${id}" block. Edit it and kit:add/kit:remove leave it to you.`;
const STARTER_HEADER =
  "// Generated by kit:add: the starter's default, until a block replaces it. Edit it and kit:add/kit:remove leave it to you.";

const ERROR_FILE = 'app/[lang]/error.tsx';
const NOT_FOUND_FILE = 'app/[lang]/not-found.tsx';
const GLOBAL_NOT_FOUND_FILE = 'app/global-not-found.tsx';

const starterDefault = (template: string) => `${STARTER_HEADER}\n${readFileSync(path.join(TEMPLATES, template), 'utf8')}`;

/** `notFound.title` as a property path on the block's JSON copy (`.notFound.title`, `['a-b']` where needed). */
const property = (key: string) =>
  key
    .split('.')
    .map((part) => (/^[A-Za-z_$][\w$]*$/.test(part) ? `.${part}` : `['${part}']`))
    .join('');

const copyImports = (id: string) => [`import ar from '@locales/ar/block-${id}.json';`, `import en from '@locales/en/block-${id}.json';`];

/** Where a block route lives: inside the app shell under (app), on its own under [lang]; `:id` becomes `[id]`. */
export const routeFile = (route: BlockRoute): string => {
  const segments = route.path
    .split('/')
    .filter(Boolean)
    .map((segment) => (segment.startsWith(':') ? `[${segment.slice(1)}]` : segment));
  return [route.layout === 'app' ? 'app/[lang]/(app)' : 'app/[lang]', ...segments, 'page.tsx'].join('/');
};

/** A server page: the title from the block's copy, the session checked inside the shell, the block's page rendered. */
const pageSource = (block: BlockMeta, route: BlockRoute): string => {
  const inShell = route.layout === 'app';
  const needsParams = inShell || !!route.titleKey;
  return [
    blockHeader(block.id),
    ...(route.titleKey ? ["import type { Metadata } from 'next';", ''] : []),
    `import { ${route.component} } from '@blocks/${block.id}';`,
    ...(route.titleKey ? copyImports(block.id) : []),
    ...(inShell ? ['', "import { isLang } from '@env';", "import { requireSession } from '@server/session';"] : []),
    '',
    ...(needsParams ? ['type PageProps = { params: Promise<{ lang: string }> };', ''] : []),
    ...(route.titleKey
      ? [
          'export async function generateMetadata({ params }: PageProps): Promise<Metadata> {',
          '  const { lang } = await params;',
          `  return { title: (lang === 'ar' ? ar : en)${property(route.titleKey)} };`,
          '}',
          '',
        ]
      : []),
    ...(inShell
      ? [
          'export default async function Page({ params }: PageProps) {',
          '  const { lang } = await params;',
          '  if (isLang(lang)) await requireSession(lang);',
        ]
      : ['export default function Page() {']),
    `  return <${route.component} />;`,
    '}',
    '',
  ].join('\n');
};

/** A URL no route matches: the block's 404 page, server-rendered in the app's providers (outside the [lang] layout). */
const globalNotFoundSource = (block: BlockMeta, route: BlockRoute): string =>
  [
    blockHeader(block.id),
    "import type { Metadata } from 'next';",
    "import { headers } from 'next/headers';",
    '',
    `import { ${route.component} } from '@blocks/${block.id}';`,
    "import { LOCALES } from '@locales';",
    ...copyImports(block.id),
    '',
    "import { DEFAULT_LANG, dirOf, isLang } from '@env';",
    '',
    "import { Providers } from './[lang]/providers';",
    "import { fontVariables } from './fonts';",
    "import { THEME_SCRIPT } from './theme-script';",
    '',
    "import '../src/index.css';",
    '',
    '/** The visitor\'s language, from the path the proxy saw ("/ar/…"), since no route (and no [lang] param) matched. */',
    'async function languageOf() {',
    "  const first = ((await headers()).get('x-pathname') ?? '').split(/[/?#]/)[1];",
    '  return isLang(first) ? first : DEFAULT_LANG;',
    '}',
    '',
    ...(route.titleKey
      ? [
          'export async function generateMetadata(): Promise<Metadata> {',
          '  const lang = await languageOf();',
          `  return { title: \`\${(lang === 'ar' ? ar : en)${property(route.titleKey)}} · RSK\` };`,
          '}',
          '',
        ]
      : []),
    'export default async function GlobalNotFound() {',
    '  const lang = await languageOf();',
    '',
    '  return (',
    '    <html lang={lang} dir={dirOf(lang)} style={fontVariables} suppressHydrationWarning>',
    '      <head>',
    '        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />',
    '      </head>',
    '      <body>',
    "        <Providers lang={lang} resources={LOCALES[lang === 'ar' ? 'AR' : 'EN']}>",
    `          <${route.component} />`,
    '        </Providers>',
    '      </body>',
    '    </html>',
    '  );',
    '}',
    '',
  ].join('\n');

/** notFound() from a page lands here; Next renders it in the browser (global-not-found.tsx is the server-rendered 404). */
const notFoundSource = (block: BlockMeta, route: BlockRoute): string =>
  [
    blockHeader(block.id),
    "'use client';",
    '',
    `import { ${route.component} } from '@blocks/${block.id}';`,
    '',
    'export default function NotFound() {',
    `  return <${route.component} />;`,
    '}',
    '',
  ].join('\n');

/** A page that fails to render: the block's error page, and "Try again" re-renders the page (Next's reset). */
const errorSource = (block: BlockMeta, component: string): string =>
  [
    blockHeader(block.id),
    "'use client';",
    '',
    `import { ${component} } from '@blocks/${block.id}';`,
    '',
    'export default function ErrorPage({ error, reset }: { error: Error & { digest?: string }; reset: () => void }) {',
    `  return <${component} error={error} retry={reset} />;`,
    '}',
    '',
  ].join('\n');

/** Every generated file and its contents: the 404 and error files (a block's or the starter's), and each block route's page. */
export function nextRouteFiles(blocks: BlockMeta[]): Map<string, string> {
  const files = new Map<string, string>();
  const catchAll = blocks.flatMap((block) => block.routes.filter((route) => route.path === '*').map((route) => ({ block, route })))[0];
  const errorBlock = blocks.find((block) => block.errorElement);
  files.set(
    GLOBAL_NOT_FOUND_FILE,
    catchAll ? globalNotFoundSource(catchAll.block, catchAll.route) : starterDefault('global-not-found.template'),
  );
  files.set(NOT_FOUND_FILE, catchAll ? notFoundSource(catchAll.block, catchAll.route) : starterDefault('not-found.template'));
  files.set(ERROR_FILE, errorBlock?.errorElement ? errorSource(errorBlock, errorBlock.errorElement) : starterDefault('error.template'));
  for (const block of blocks)
    for (const route of block.routes.filter((entry) => entry.path !== '*')) files.set(routeFile(route), pageSource(block, route));
  return files;
}

export type RoutePlan = {
  /** Files to write: missing, or still exactly as kit:add wrote them. */
  write: Map<string, string>;
  /** Generated files no block wants any more, unchanged since kit:add wrote them. */
  remove: string[];
  /** Files in the way that are the app's: never written by kit:add, or changed since. */
  refused: string[];
};

/** What writeBlockRoutes would do for `blocks`, without touching anything. */
export function planBlockRoutes(appDir: string, blocks: BlockMeta[]): RoutePlan {
  const recorded = readLock(appDir).generated ?? {};
  const wanted = nextRouteFiles(blocks);
  const current = (file: string) => (existsSync(path.join(appDir, file)) ? readFileSync(path.join(appDir, file), 'utf8') : undefined);
  const unchanged = (file: string) => recorded[file] !== undefined && hashFile(path.join(appDir, file)) === recorded[file];
  const plan: RoutePlan = { write: new Map(), remove: [], refused: [] };
  for (const [file, source] of wanted) {
    const existing = current(file);
    if (existing === source) continue;
    if (existing === undefined || unchanged(file)) plan.write.set(file, source);
    else plan.refused.push(file);
  }
  for (const file of Object.keys(recorded).filter((name) => !wanted.has(name))) {
    if (current(file) === undefined) continue;
    if (unchanged(file)) plan.remove.push(file);
    else plan.refused.push(file);
  }
  return plan;
}

/** Removes `dir` and its parents up to app/ while they are empty. */
const pruneEmpty = (appDir: string, dir: string) => {
  for (let at = dir; at !== 'app' && at.startsWith('app/'); at = path.posix.dirname(at)) {
    const full = path.join(appDir, at);
    if (!existsSync(full) || readdirSync(full).length) return;
    rmSync(full, { recursive: true });
  }
};

/**
 * Writes the generated files `blocks` need and removes the ones no longer wanted, skipping the app's own. Returns the
 * hashes to record as the lock's `generated`, and the files kept because the app changed them.
 */
export function writeBlockRoutes(appDir: string, blocks: BlockMeta[]): { generated: Record<string, string>; kept: string[] } {
  const plan = planBlockRoutes(appDir, blocks);
  for (const [file, source] of plan.write) {
    mkdirSync(path.dirname(path.join(appDir, file)), { recursive: true });
    writeFileSync(path.join(appDir, file), source);
  }
  for (const file of plan.remove) {
    rmSync(path.join(appDir, file));
    pruneEmpty(appDir, path.posix.dirname(file));
  }
  const generated = Object.fromEntries(
    [...nextRouteFiles(blocks).keys()]
      .filter((file) => !plan.refused.includes(file) && existsSync(path.join(appDir, file)))
      .map((file) => [file, hashFile(path.join(appDir, file))]),
  );
  return { generated, kept: plan.refused };
}
